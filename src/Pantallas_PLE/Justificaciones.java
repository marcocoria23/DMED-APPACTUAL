    public void Muestra_tabla() {
    Querys Q = new Querys();
    ArrayList<String[]> datos = Q.Justificaciones(
            CEntidad.getSelectedItem().toString(),
            CLegislatura.getSelectedItem().toString(),
            TEnvio.getSelectedItem().toString());
    String[] columnas = {
        "TABLA",
        "ID_TABLA",
        "CAMPO",
        "VALOR_CAMPO",
        "OBSERVACION",
        "JUSTIFICACION",
        "VALOR_INSERTADO",
        "ID_UNIQUE"
    };
    DefaultTableModel modelo = new DefaultTableModel(columnas, 0) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false; // Ninguna celda será editable
        }
    };
    for (String[] fila : datos) {
        modelo.addRow(fila);
    }
    jTable1.setModel(modelo);
     // Ocultar la columna ID_UNIQUE
    jTable1.getColumnModel().getColumn(7).setMinWidth(0);
    jTable1.getColumnModel().getColumn(7).setMaxWidth(0);
    jTable1.getColumnModel().getColumn(7).setWidth(0);
    jTable1.getColumnModel().getColumn(7).setPreferredWidth(0);
}
    
