    private void jTable1MousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MousePressed
        // TODO add your handling code here:
        VNuevo=false;
        int selectedRowIndex = jTable1.getSelectedRow();
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        if (evt.getClickCount() == 2) {
            DENTIDAD = CEntidad.getSelectedItem().toString();
            DLEGISLATURA = CLegislatura.getSelectedItem().toString();
            DENVIO = TEnvio.getSelectedItem().toString();
            Object valor;
            valor = model.getValueAt(selectedRowIndex, 0);
            if (valor != null) {
                DTABLA = valor.toString();
            } else {
                DTABLA = "";
            }
            valor = model.getValueAt(selectedRowIndex, 1);
            if (valor != null) {
                DID_TABLA = valor.toString();
            } else {
                DID_TABLA = "";
            }
            valor = model.getValueAt(selectedRowIndex, 2);
            if (valor != null) {
                DCAMPO = valor.toString();
            } else {
                DCAMPO = "";
            }
            valor = model.getValueAt(selectedRowIndex, 3);
            if (valor != null) {
                DVALOR_CAMPO = valor.toString();
            } else {
                DVALOR_CAMPO = "";
            }
            valor = model.getValueAt(selectedRowIndex, 4);
            if (valor != null) {
                DOBSERVACION = valor.toString();
            } else {
                DOBSERVACION = "";
            }
            valor = model.getValueAt(selectedRowIndex, 5);
            if (valor != null) {
                DJUSTIFICACION = valor.toString();
            } else {
                DJUSTIFICACION = "";
            }
            valor = model.getValueAt(selectedRowIndex, 6);
            if (valor != null) {
                DVALOR_INSERTADO = valor.toString();
            } else {
                DVALOR_INSERTADO = "";
            }
            valor = model.getValueAt(selectedRowIndex, 7);
            if (valor != null) {
                DID_UNIQUE = valor.toString();
            } else {
                DID_UNIQUE = "";
            }
            Justificaciones_Cambios CCambio = new Justificaciones_Cambios();
            CCambio.setVisible(true);
        }
    }//GEN-LAST:event_jTable1MousePressed

